-- PostgreSQL schema for Replit's managed database.
-- Apply to a new development database; Publish carries the schema to production.
BEGIN;

CREATE TABLE IF NOT EXISTS schema_migrations (
  version VARCHAR(120) PRIMARY KEY,
  applied_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(254) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role TEXT NOT NULL DEFAULT 'user' CHECK (role IN ('user','admin')),
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','suspended')),
  email_verified_at TIMESTAMP NULL,
  last_login_at TIMESTAMP NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_users_status_role ON users(status, role);
CREATE INDEX IF NOT EXISTS idx_users_created ON users(created_at);

CREATE TABLE IF NOT EXISTS profiles (
  user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  display_name VARCHAR(80) NOT NULL,
  free_fire_uid VARCHAR(32) NULL UNIQUE,
  avatar_path VARCHAR(255) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS teams (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(60) NOT NULL,
  captain_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_teams_captain_name UNIQUE (captain_id, name)
);
CREATE INDEX IF NOT EXISTS idx_teams_captain ON teams(captain_id);

CREATE TABLE IF NOT EXISTS team_members (
  team_id BIGINT NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  member_role TEXT NOT NULL DEFAULT 'member' CHECK (member_role IN ('captain','member')),
  joined_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (team_id, user_id),
  CONSTRAINT uq_team_member_user UNIQUE (user_id, team_id)
);
CREATE INDEX IF NOT EXISTS idx_team_members_user ON team_members(user_id);

CREATE TABLE IF NOT EXISTS team_invitations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  team_id BIGINT NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
  inviter_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  invitee_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','accepted','rejected','cancelled','expired')),
  invited_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  responded_at TIMESTAMP NULL,
  expires_at TIMESTAMP NOT NULL,
  CONSTRAINT uq_team_invitation UNIQUE (team_id, invitee_id)
);
CREATE INDEX IF NOT EXISTS idx_invitations_inbox ON team_invitations(invitee_id, status, expires_at);
CREATE INDEX IF NOT EXISTS idx_invitations_team ON team_invitations(team_id, status);

CREATE TABLE IF NOT EXISTS tournaments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug VARCHAR(120) NOT NULL UNIQUE,
  title VARCHAR(140) NOT NULL,
  description TEXT NOT NULL,
  map_name VARCHAR(60) NOT NULL,
  mode TEXT NOT NULL CHECK (mode IN ('solo','duo','squad')),
  team_size SMALLINT NOT NULL CHECK (team_size >= 0),
  entry_fee_minor BIGINT NOT NULL DEFAULT 0 CHECK (entry_fee_minor >= 0),
  prize_pool_minor BIGINT NOT NULL DEFAULT 0 CHECK (prize_pool_minor >= 0),
  participant_limit INTEGER NOT NULL CHECK (participant_limit >= 0),
  registration_deadline TIMESTAMP NOT NULL,
  match_time TIMESTAMP NOT NULL,
  room_release_at TIMESTAMP NOT NULL,
  rules TEXT NOT NULL,
  banner_path VARCHAR(255) NULL,
  room_id_enc BYTEA NULL,
  room_id_iv BYTEA NULL,
  room_id_tag BYTEA NULL,
  room_password_enc BYTEA NULL,
  room_password_iv BYTEA NULL,
  room_password_tag BYTEA NULL,
  status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','open','locked','live','completed','cancelled')),
  results_status TEXT NOT NULL DEFAULT 'none' CHECK (results_status IN ('none','provisional','final')),
  tie_breakers JSONB NOT NULL,
  created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  results_published_at TIMESTAMP NULL,
  auto_prizes_enabled SMALLINT NOT NULL DEFAULT 0 CHECK (auto_prizes_enabled IN (0,1)),
  rank_prize_percentages JSONB NULL,
  kill_reward_per_kill_minor BIGINT NOT NULL DEFAULT 0 CHECK (kill_reward_per_kill_minor >= 0),
  payouts_locked_at TIMESTAMP NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_tournament_team_size CHECK (
    (mode = 'solo' AND team_size = 1) OR
    (mode = 'duo' AND team_size = 2) OR
    (mode = 'squad' AND team_size = 4)
  )
);
CREATE INDEX IF NOT EXISTS idx_tournaments_browse ON tournaments(status, match_time);
CREATE INDEX IF NOT EXISTS idx_tournaments_deadline ON tournaments(status, registration_deadline);
CREATE INDEX IF NOT EXISTS idx_tournaments_mode ON tournaments(mode, status, match_time);

CREATE TABLE IF NOT EXISTS scoring_rules (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tournament_id BIGINT NOT NULL REFERENCES tournaments(id) ON DELETE CASCADE,
  placement_rank INTEGER NOT NULL DEFAULT 0 CHECK (placement_rank >= 0),
  placement_points INTEGER NOT NULL DEFAULT 0,
  points_per_kill INTEGER NOT NULL DEFAULT 1 CHECK (points_per_kill >= 0),
  active SMALLINT NOT NULL DEFAULT 1 CHECK (active IN (0,1)),
  tie_breakers JSONB NOT NULL,
  placement_multiplier SMALLINT NOT NULL DEFAULT 1 CHECK (placement_multiplier >= 0),
  bonus_multiplier SMALLINT NOT NULL DEFAULT 1 CHECK (bonus_multiplier >= 0),
  penalty_multiplier SMALLINT NOT NULL DEFAULT 1 CHECK (penalty_multiplier >= 0),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_scoring_tournament_rank UNIQUE (tournament_id, placement_rank)
);

CREATE TABLE IF NOT EXISTS registrations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tournament_id BIGINT NOT NULL REFERENCES tournaments(id) ON DELETE RESTRICT,
  captain_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  team_id BIGINT NULL REFERENCES teams(id) ON DELETE RESTRICT,
  entry_fee_minor BIGINT NOT NULL CHECK (entry_fee_minor >= 0),
  status TEXT NOT NULL DEFAULT 'confirmed' CHECK (status IN ('confirmed','cancelled','refunded')),
  idempotency_key VARCHAR(100) NOT NULL UNIQUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  cancelled_at TIMESTAMP NULL,
  CONSTRAINT uq_registration_team UNIQUE (tournament_id, team_id)
);
CREATE INDEX IF NOT EXISTS idx_registration_tournament_status ON registrations(tournament_id, status);
CREATE INDEX IF NOT EXISTS idx_registration_captain ON registrations(captain_id, created_at);

CREATE TABLE IF NOT EXISTS registration_members (
  registration_id BIGINT NOT NULL REFERENCES registrations(id) ON DELETE CASCADE,
  tournament_id BIGINT NOT NULL REFERENCES tournaments(id) ON DELETE RESTRICT,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  PRIMARY KEY (registration_id, user_id),
  CONSTRAINT uq_tournament_registration_user UNIQUE (tournament_id, user_id)
);
CREATE INDEX IF NOT EXISTS idx_registration_members_user ON registration_members(user_id, registration_id);

CREATE TABLE IF NOT EXISTS matches (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tournament_id BIGINT NOT NULL REFERENCES tournaments(id) ON DELETE CASCADE,
  match_number SMALLINT NOT NULL CHECK (match_number >= 0),
  starts_at TIMESTAMP NULL,
  status TEXT NOT NULL DEFAULT 'scheduled' CHECK (status IN ('scheduled','live','completed','cancelled')),
  note VARCHAR(500) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_tournament_match_number UNIQUE (tournament_id, match_number)
);

CREATE TABLE IF NOT EXISTS results (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tournament_id BIGINT NOT NULL REFERENCES tournaments(id) ON DELETE RESTRICT,
  match_id BIGINT NOT NULL REFERENCES matches(id) ON DELETE RESTRICT,
  registration_id BIGINT NOT NULL REFERENCES registrations(id) ON DELETE RESTRICT,
  placement_rank INTEGER NOT NULL CHECK (placement_rank >= 0),
  kills SMALLINT NOT NULL DEFAULT 0 CHECK (kills >= 0),
  bonus_points INTEGER NOT NULL DEFAULT 0 CHECK (bonus_points >= 0),
  penalty_points INTEGER NOT NULL DEFAULT 0 CHECK (penalty_points >= 0),
  placement_points INTEGER NOT NULL DEFAULT 0,
  kill_points INTEGER NOT NULL DEFAULT 0,
  total_points INTEGER NOT NULL DEFAULT 0,
  entered_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  updated_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  bonus_input INTEGER NOT NULL DEFAULT 0 CHECK (bonus_input >= 0),
  penalty_input INTEGER NOT NULL DEFAULT 0 CHECK (penalty_input >= 0),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_match_registration_result UNIQUE (match_id, registration_id)
);
CREATE INDEX IF NOT EXISTS idx_results_leaderboard ON results(tournament_id, registration_id);
CREATE INDEX IF NOT EXISTS idx_results_match_rank ON results(match_id, placement_rank);

CREATE TABLE IF NOT EXISTS wallet_accounts (
  user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE RESTRICT,
  balance_minor BIGINT NOT NULL DEFAULT 0 CHECK (balance_minor >= 0),
  reserved_minor BIGINT NOT NULL DEFAULT 0 CHECK (reserved_minor >= 0),
  currency CHAR(3) NOT NULL DEFAULT 'INR',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS wallet_transactions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  transaction_type TEXT NOT NULL CHECK (transaction_type IN ('deposit','entry_fee','entry_refund','prize','withdrawal_reserve','withdrawal_release','withdrawal_paid','admin_adjustment')),
  amount_minor BIGINT NOT NULL CHECK (amount_minor >= 0),
  available_delta_minor BIGINT NOT NULL,
  reserved_delta_minor BIGINT NOT NULL DEFAULT 0,
  available_after_minor BIGINT NOT NULL CHECK (available_after_minor >= 0),
  reserved_after_minor BIGINT NOT NULL CHECK (reserved_after_minor >= 0),
  status TEXT NOT NULL DEFAULT 'posted' CHECK (status IN ('posted','reversed')),
  idempotency_key VARCHAR(140) NOT NULL UNIQUE,
  reference_type VARCHAR(40) NULL,
  reference_id BIGINT NULL,
  note VARCHAR(255) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_wallet_user_time ON wallet_transactions(user_id, created_at);
CREATE INDEX IF NOT EXISTS idx_wallet_reference ON wallet_transactions(reference_type, reference_id);

CREATE TABLE IF NOT EXISTS withdrawal_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  amount_minor BIGINT NOT NULL CHECK (amount_minor >= 0),
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','processing','paid','rejected')),
  payout_method TEXT NOT NULL DEFAULT 'upi' CHECK (payout_method IN ('upi')),
  payout_details_enc BYTEA NOT NULL,
  payout_details_iv BYTEA NOT NULL,
  payout_details_tag BYTEA NOT NULL,
  payout_reference VARCHAR(140) NULL,
  idempotency_key VARCHAR(120) NOT NULL UNIQUE,
  reviewed_by BIGINT NULL REFERENCES users(id) ON DELETE RESTRICT,
  reviewed_at TIMESTAMP NULL,
  paid_at TIMESTAMP NULL,
  rejection_reason VARCHAR(255) NULL,
  gst_minor BIGINT NOT NULL DEFAULT 0 CHECK (gst_minor >= 0),
  net_amount_minor BIGINT NOT NULL DEFAULT 0 CHECK (net_amount_minor >= 0),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_withdrawal_queue ON withdrawal_requests(status, created_at);
CREATE INDEX IF NOT EXISTS idx_withdrawal_user ON withdrawal_requests(user_id, created_at);

CREATE TABLE IF NOT EXISTS notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  notification_type VARCHAR(50) NOT NULL,
  title VARCHAR(120) NOT NULL,
  body VARCHAR(500) NOT NULL,
  target_url VARCHAR(255) NULL,
  read_at TIMESTAMP NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_notifications_user_unread ON notifications(user_id, read_at, created_at);

CREATE TABLE IF NOT EXISTS announcements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(140) NOT NULL,
  body TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','published','archived')),
  published_at TIMESTAMP NULL,
  created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_announcements_public ON announcements(status, published_at);

CREATE TABLE IF NOT EXISTS support_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NULL REFERENCES users(id) ON DELETE SET NULL,
  contact_email VARCHAR(254) NOT NULL,
  subject VARCHAR(140) NOT NULL,
  message TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open','in_progress','resolved','closed')),
  assigned_to BIGINT NULL REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_support_queue ON support_requests(status, created_at);
CREATE INDEX IF NOT EXISTS idx_support_user ON support_requests(user_id, created_at);

CREATE TABLE IF NOT EXISTS settings (
  setting_key VARCHAR(100) PRIMARY KEY,
  setting_value TEXT NOT NULL,
  updated_by BIGINT NULL REFERENCES users(id) ON DELETE SET NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id BIGINT NULL REFERENCES users(id) ON DELETE SET NULL,
  action VARCHAR(100) NOT NULL,
  entity_type VARCHAR(50) NOT NULL,
  entity_id BIGINT NULL,
  before_data JSONB NULL,
  after_data JSONB NULL,
  ip_address BYTEA NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_audit_actor_time ON audit_logs(actor_id, created_at);
CREATE INDEX IF NOT EXISTS idx_audit_entity ON audit_logs(entity_type, entity_id, created_at);

CREATE TABLE IF NOT EXISTS rate_limits (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scope_key CHAR(64) NOT NULL,
  window_started_at TIMESTAMP NOT NULL,
  attempts INTEGER NOT NULL DEFAULT 1 CHECK (attempts >= 0),
  CONSTRAINT uq_rate_limit_scope_window UNIQUE (scope_key, window_started_at)
);
CREATE INDEX IF NOT EXISTS idx_rate_limits_expiry ON rate_limits(window_started_at);

CREATE TABLE IF NOT EXISTS deposit_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  amount_minor BIGINT NOT NULL CHECK (amount_minor >= 0),
  utr_number VARCHAR(120) NOT NULL UNIQUE,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected')),
  idempotency_key VARCHAR(140) NOT NULL UNIQUE,
  review_note VARCHAR(255) NULL,
  reviewed_by BIGINT NULL REFERENCES users(id) ON DELETE RESTRICT,
  reviewed_at TIMESTAMP NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_deposit_requests_queue ON deposit_requests(status, created_at);
CREATE INDEX IF NOT EXISTS idx_deposit_requests_user ON deposit_requests(user_id, created_at);

CREATE OR REPLACE FUNCTION victory_yudh_touch_updated_at()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$;
CREATE TRIGGER users_touch_updated_at BEFORE UPDATE ON users FOR EACH ROW EXECUTE FUNCTION victory_yudh_touch_updated_at();
CREATE TRIGGER profiles_touch_updated_at BEFORE UPDATE ON profiles FOR EACH ROW EXECUTE FUNCTION victory_yudh_touch_updated_at();
CREATE TRIGGER teams_touch_updated_at BEFORE UPDATE ON teams FOR EACH ROW EXECUTE FUNCTION victory_yudh_touch_updated_at();
CREATE TRIGGER tournaments_touch_updated_at BEFORE UPDATE ON tournaments FOR EACH ROW EXECUTE FUNCTION victory_yudh_touch_updated_at();
CREATE TRIGGER scoring_rules_touch_updated_at BEFORE UPDATE ON scoring_rules FOR EACH ROW EXECUTE FUNCTION victory_yudh_touch_updated_at();
CREATE TRIGGER matches_touch_updated_at BEFORE UPDATE ON matches FOR EACH ROW EXECUTE FUNCTION victory_yudh_touch_updated_at();
CREATE TRIGGER results_touch_updated_at BEFORE UPDATE ON results FOR EACH ROW EXECUTE FUNCTION victory_yudh_touch_updated_at();
CREATE TRIGGER wallet_accounts_touch_updated_at BEFORE UPDATE ON wallet_accounts FOR EACH ROW EXECUTE FUNCTION victory_yudh_touch_updated_at();
CREATE TRIGGER withdrawal_requests_touch_updated_at BEFORE UPDATE ON withdrawal_requests FOR EACH ROW EXECUTE FUNCTION victory_yudh_touch_updated_at();
CREATE TRIGGER announcements_touch_updated_at BEFORE UPDATE ON announcements FOR EACH ROW EXECUTE FUNCTION victory_yudh_touch_updated_at();
CREATE TRIGGER support_requests_touch_updated_at BEFORE UPDATE ON support_requests FOR EACH ROW EXECUTE FUNCTION victory_yudh_touch_updated_at();
CREATE TRIGGER settings_touch_updated_at BEFORE UPDATE ON settings FOR EACH ROW EXECUTE FUNCTION victory_yudh_touch_updated_at();
